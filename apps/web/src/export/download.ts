// Trigger a browser file download for generated text (exports stay local; the
// data never leaves the machine). Used by the Review tab's GEDCOM/JSON exports
// and the locality research report.

export function triggerDownload(filename: string, content: string, mime: string): void {
  const blob = new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}
